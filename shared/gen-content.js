// Builds shared/yd-content-catalog.js: every built-in text of the website, customer app and driver app
// (English + Dhivehi), which the console's Content page lists for editing.
// Run after changing app texts:  node shared/gen-content.js   (needs Playwright; serves the repo itself)
const http = require("http"), fs = require("fs"), path = require("path");
const { chromium } = require("playwright");
const ROOT = path.resolve(__dirname, "..");
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".jpg": "image/jpeg", ".png": "image/png", ".svg": "image/svg+xml", ".woff2": "font/woff2", ".json": "application/json" };
const server = http.createServer((req, res) => {
  const f = path.join(ROOT, decodeURIComponent(req.url.split("?")[0]));
  if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { "Content-Type": TYPES[path.extname(f)] || "application/octet-stream" }); fs.createReadStream(f).pipe(res);
});
(async () => {
  await new Promise(r => server.listen(0, r));
  const port = server.address().port, browser = await chromium.launch(), out = {};
  for (const [id, dir] of [["website", "website"], ["customer_app", "customer-app"], ["driver_app", "driver-app"]]) {
    const page = await browser.newPage();
    await page.route(/^https?:\/\/(?!localhost)/, r => r.abort());          // no network needed
    await page.addInitScript(() => { try { localStorage.removeItem("yd-demo-settings"); } catch (e) {} });
    await page.goto(`http://localhost:${port}/${dir}/index.html`);
    await page.waitForTimeout(1200);
    const d = await page.evaluate(() => YDUI.i18n.dump());
    // drop the shared theme labels and anything that isn't text
    const keys = Object.keys(d.en).filter(k => !/^theme\./.test(k) && typeof d.en[k] === "string").sort();
    out[id] = {};
    keys.forEach(k => { out[id][k] = [d.en[k], d.dv[k] || ""]; });
    console.log(id, keys.length, "texts");
    await page.close();
  }
  await browser.close(); server.close();
  const js = "/* generated by shared/gen-content.js — every built-in text: { surface: { key: [english, dhivehi] } } */\n" +
             "window.YD_CONTENT_CATALOG=" + JSON.stringify(out) + ";\n";
  fs.writeFileSync(path.join(__dirname, "yd-content-catalog.js"), js);
  console.log("wrote shared/yd-content-catalog.js", Math.round(js.length / 1024), "KB");
})();
