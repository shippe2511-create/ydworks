// Regenerates the catalog seed migration from shared/yd-catalog.js so the database,
// website, apps and console always start from the same names, specs and prices.
// Run: node shared/gen-seed.js
const fs = require("fs"), path = require("path");
const c = require("./yd-catalog.js");
const q = v => "'" + String(v).replace(/'/g, "''") + "'";
const machines = c.machines.map(m => ` (${q(m.id)},${q(m.code)},${q(m.name)},${q(m.category)},${q(m.icon)},${q(JSON.stringify(m.specs))},${m.rate_hr},${m.rate_day},${m.rate_mo},${m.sort})`).join(",\n");
const materials = c.materials.map(m => ` (${q(m.id)},${q(m.name)},${q(m.category)},${q(m.unit)},${m.price},${m.step},${q(m.icon)},${m.sort})`).join(",\n");
const sql = `-- GENERATED by shared/gen-seed.js from shared/yd-catalog.js. Do not edit by hand.
-- PRICES ARE SAMPLE FIGURES: update them in the YD Works Console (Fleet & materials).
insert into public.machines (id, code, name, category, icon, specs, rate_hr, rate_day, rate_mo, sort) values
${machines}
on conflict (id) do update set code=excluded.code, name=excluded.name, category=excluded.category, icon=excluded.icon, specs=excluded.specs, sort=excluded.sort;

insert into public.materials (id, name, category, unit, price, step, icon, sort) values
${materials}
on conflict (id) do update set name=excluded.name, category=excluded.category, unit=excluded.unit, step=excluded.step, icon=excluded.icon, sort=excluded.sort;
`;
fs.writeFileSync(path.join(__dirname, "..", "supabase", "migrations", "20261124000002_ydworks_catalog_seed.sql"), sql);
console.log("seed written:", c.machines.length, "machines,", c.materials.length, "materials");
